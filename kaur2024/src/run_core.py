"""Core experiments (seed 0): E1 IID-DQN, E2 non-IID-DQN, FedAvg IID, FedAvg non-IID.
Writes kaur2024/results/core/core_tables.md in the formats of Table VIII (best/worst/global at
rounds 1, 50 [PAPER] and 100 [EXTRA]) and Table V (per-class P/R/F1, macro, accuracy) + AUC and
energy. Unseen-subset scores [GAP-FILL G17] are reported in a separate table.

  python kaur2024/src/run_core.py [--csv PATH] [--parallel 2] [--smoke N] [--tables-only]
--smoke N runs every core config for N rounds only (separate *_smokeN folders, no tables).
"""
import argparse

from runner_utils import CLASS_NAMES, launch, load_round, pct, repo_path, scalar_metrics

CORE = ["e1_iid_dqn", "e2_noniid_dqn", "fedavg_iid", "fedavg_noniid"]


def tables():
    L = ["# Core results (training seed 0)", "",
         "Generated by `python kaur2024/src/run_core.py --tables-only`. Paper reference values: "
         "Table V (TON_IoT, proposed: acc 99.95; implied by its per-class rows: 96.47, see X4). "
         "Table VIII has no TON_IoT numbers (it is Edge-IIoT; SPEC C1).", "",
         "## Table VIII format: accuracy (%) of best client, worst client and global model", "",
         "| config | R1 best | R1 worst | R1 global | R50 best | R50 worst | R50 global | R100 best | R100 worst | R100 global | status |",
         "|---|---|---|---|---|---|---|---|---|---|---|"]
    for c in CORE:
        row, status = [], "missing"
        for r in (1, 50, 100):
            m = load_round(c, 0, r)
            if m:
                status = m["status"]
                row += [pct(m["best_client_acc"]), pct(m["worst_client_acc"]), pct(m["global"]["accuracy"])]
            else:
                row += ["n/a"] * 3
        L.append(f"| {c} | " + " | ".join(row) + f" | {status} |")
    for r in (50, 100):
        L += ["", f"## Table V format, round {r} (%; energy = cumulative C_training in J, Eq. 4)", "",
              "| config | metric | " + " | ".join(CLASS_NAMES) + " | macro | acc | AUC (macro OvR) | energy (J) |",
              "|---|---|" + "---|" * (len(CLASS_NAMES) + 4)]
        for c in CORE:
            m = load_round(c, 0, r)
            if not m:
                L.append(f"| {c} | n/a |" + " |" * (len(CLASS_NAMES) + 4)); continue
            g = m["global"]
            for key, lab in (("precision", "P"), ("recall", "R"), ("f1", "F1")):
                tail = (f" {pct(g['accuracy'])} | {pct(g['auc']['macro_ovr'])} | {m['energy_cum']:.3f} |"
                        if key == "precision" else "  |  |  |")
                L.append(f"| {c} | {lab} | " + " | ".join(pct(g["per_class"][cl][key]) for cl in CLASS_NAMES)
                         + f" | {pct(g['macro'][key])} |" + tail)
    L += ["", "## [GAP-FILL G17] unseen test subset (test rows whose features never occur in train)", "",
          "| config | R50 acc | R50 macro F1 | R100 acc | R100 macro F1 | n rows |", "|---|---|---|---|---|---|"]
    for c in CORE:
        cells, n = [], "n/a"
        for r in (50, 100):
            m = load_round(c, 0, r)
            if m:
                u = m["global_unseen_subset"]; n = u["n"]
                cells += [pct(u.get("accuracy")), pct((u.get("macro") or {}).get("f1"))]
            else:
                cells += ["n/a", "n/a"]
        L.append(f"| {c} | " + " | ".join(cells) + f" | {n} |")
    out = repo_path("kaur2024/results/core/core_tables.md")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--csv"); ap.add_argument("--parallel", type=int, default=2)
    ap.add_argument("--smoke", type=int); ap.add_argument("--tables-only", action="store_true")
    a = ap.parse_args()
    if not a.tables_only:
        launch([(c, 0) for c in CORE], a.parallel, a.csv, a.smoke)
    if not a.smoke:
        tables()
